"""Shadow topic prototypes and isolated Qdrant fixtures for routing evaluation.

Only a freshly named UUID evaluation collection may be written or deleted.
Production source collections are never mutated. The source topic vectors and
checksums remain in local artifacts after the temporary collection is removed.
"""
from __future__ import annotations

from contextlib import contextmanager, ExitStack
import asyncio
import argparse
from dataclasses import asdict
import json
from pathlib import Path
import time
from types import SimpleNamespace
from unittest.mock import patch
import uuid

import numpy as np

from .knowledge_routing import COLLECTIONS, coverage, load_snapshot, portrait_hits, scroll, sha, summary_portraits, write_json
from .retrieval_schema import digest, require


def prototype_points(topics_by_kb: dict) -> list[dict]:
    from app.modules.knowledge.topic_prototypes import topic_routing_vectors

    points = []
    for kb_id, topics in sorted(topics_by_kb.items()):
        for topic in topics:
            for position, vector in enumerate(topic_routing_vectors(topic)):
                topic_id = f"{kb_id}:{topic['cluster_id']}"
                points.append({
                    "id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"routing-eval:{topic_id}:{position}")),
                    "vector": vector,
                    "payload": {"kb_id": kb_id, "topic_id": topic_id, "portrait_role": "topic_prototype",
                                "cluster_size": topic["sample_support_count"], "prototype_position": position},
                })
    require(bool(points), "no prototype vectors")
    require(len({point["id"] for point in points}) == len(points), "duplicate prototype IDs")
    require(len({len(point["vector"]) for point in points}) == 1, "prototype dimensions differ")
    return points


@contextmanager
def isolated_prototype_collection(qdrant_url: str, topics_path: Path, summaries: list[dict] | None = None,
                                  *, copy_payload_indexes: bool = False):
    from qdrant_client import QdrantClient, models

    points = prototype_points(json.loads(topics_path.read_text()))
    prototype_count = len(points)
    summaries = summary_portraits(summaries or [])
    points.extend({key: row[key] for key in ("id", "vector", "payload")} for row in summaries)
    require(len({point["id"] for point in points}) == len(points), "summary and prototype point IDs collide")
    client = QdrantClient(url=qdrant_url)
    name = "eval_knowledge_routing_" + uuid.uuid4().hex
    require(not client.collection_exists(name), "evaluation collection unexpectedly already exists")
    created = False
    fixture = {"collection": name, "source_path": str(topics_path), "source_sha256": sha(topics_path),
               "points": len(points), "prototype_points": prototype_count, "summary_points": len(summaries),
               "dimensions": len(points[0]["vector"]), "deleted_after_run": False,
               "payload_indexes": {},
               "routing_policy": "coverage summary and prototype searches share isolated expanded index; baseline reads original summary index"}
    try:
        client.create_collection(name, vectors_config=models.VectorParams(size=fixture["dimensions"], distance=models.Distance.COSINE))
        created = True
        client.upsert(name, points=[models.PointStruct(**point) for point in points], wait=True)
        if copy_payload_indexes:
            source_schema = client.get_collection("kb_portraits").payload_schema
            for field, schema in source_schema.items():
                client.create_payload_index(name, field_name=field, field_schema=schema.data_type, wait=True)
                fixture["payload_indexes"][field] = schema.data_type.value
        require(client.count(name, exact=True).count == len(points), "isolated collection did not retain all prototype points")
        yield fixture
    finally:
        if created:
            # The local, unmodifiable name is generated by this context. Never
            # accept a user-supplied deletion target or delete source collections.
            client.delete_collection(name)
            fixture["deleted_after_run"] = not client.collection_exists(name)
        client.close()


async def replay(snapshot: Path, samples_path: Path, output: Path) -> dict:
    """Use production prototype construction/selection on frozen real samples."""
    from app.core.config import settings
    from app.core.logger import logger
    from app.modules.knowledge.evidence_routing import select_prototype_routes
    from app.modules.knowledge.router import KnowledgeRouter
    from app.modules.knowledge.topic_prototypes import build_topic_prototypes
    from threadpoolctl import threadpool_limits

    manifest, cases, portraits, queries, vectors = load_snapshot(snapshot)
    portraits = summary_portraits(portraits)
    require(bool(portraits), "snapshot has no summary portraits")
    vectors = np.asarray([row["vector"] for row in portraits], dtype=np.float32)
    output.mkdir(parents=True, exist_ok=False)
    topics_by_kb, build_seconds, sample_hashes = {}, {}, {}
    with threadpool_limits(limits=1):
        for path in sorted(samples_path.glob("*.json")):
            if path.name == "manifest.json":
                continue
            data = json.loads(path.read_text())
            matrix = np.load(path.with_suffix(".npy"), allow_pickle=False)
            require(len(data["samples"]) == len(matrix), "sample vector/metadata count differs")
            samples = [dict(row, vector=vector.tolist()) for row, vector in zip(data["samples"], matrix)]
            started = time.perf_counter()
            topics_by_kb[data["kb_id"]] = build_topic_prototypes(samples, data["clustering"])
            build_seconds[data["kb_id"]] = time.perf_counter() - started
            sample_hashes[path.name] = sha(path)
            sample_hashes[path.with_suffix(".npy").name] = sha(path.with_suffix(".npy"))
    write_json(output / "topics.json", topics_by_kb)
    points = prototype_points(topics_by_kb)
    prototype_vectors = np.asarray([point["vector"] for point in points], dtype=np.float32)

    async def listing(**kwargs):
        return [{"id": kb, "name": kb} for kb in sorted(topics_by_kb)]

    router = KnowledgeRouter.__new__(KnowledgeRouter)
    router.kb_service = SimpleNamespace(list_knowledge_bases=listing)
    old_mode = settings.knowledge_routing_score_mode
    policies = {}
    logger.disable("app.modules.knowledge.router")
    try:
        for name, nodes, matrix, limit, mode in (
            ("summary_legacy", portraits, vectors, 30, "legacy"),
            ("summary_max", portraits, vectors, 30, "max"),
            ("prototype_max", points, prototype_vectors, len(points), "max"),
            ("combined_max", portraits + points, np.vstack([vectors, prototype_vectors]), len(portraits) + len(points), "max"),
        ):
            settings.knowledge_routing_score_mode = mode
            records = []
            for case, hits in zip(cases, portrait_hits(queries, matrix, nodes, limit)):
                scores = router._calculate_multi_signal_scores([hits])
                selection = await router._apply_routing_strategy(scores, max_targets=2)
                records.append({"id": case["id"], "target_kb_ids": selection.target_kb_ids, "scores": scores,
                                "coverage": coverage(case, selection.target_kb_ids)})
            policies[name] = {"cases": records}
        records = []
        for case, baseline, prototypes in zip(cases, policies["summary_legacy"]["cases"], policies["prototype_max"]["cases"]):
            selection = select_prototype_routes(baseline["target_kb_ids"], prototypes["scores"], max_targets=2)
            records.append({"id": case["id"], "target_kb_ids": selection.targets, "details": selection.details,
                            "coverage": coverage(case, selection.targets)})
        policies["coverage"] = {"cases": records}
        baseline = {record["id"]: record for record in policies["summary_legacy"]["cases"]}
        for policy in policies.values():
            policy.update(
                coverage=sum(row["coverage"]["all_groups"] for row in policy["cases"]),
                mean_targets=float(np.mean([len(row["target_kb_ids"]) for row in policy["cases"]])),
                improved=[row["id"] for row in policy["cases"] if row["coverage"]["group_recall"] > baseline[row["id"]]["coverage"]["group_recall"]],
                regressed=[row["id"] for row in policy["cases"] if row["coverage"]["group_recall"] < baseline[row["id"]]["coverage"]["group_recall"]],
            )
    finally:
        settings.knowledge_routing_score_mode = old_mode
        logger.enable("app.modules.knowledge.router")
    report = {"schema_version": "knowledge-routing-prototype-replay-1", "policies": policies,
              "snapshot_manifest_sha256": sha(snapshot / "manifest.json"), "sample_hashes": sample_hashes,
              "prototype_vectors": len(points), "prototype_topics": sum(map(len, topics_by_kb.values())),
              "build_seconds": build_seconds, "topics_sha256": sha(output / "topics.json"),
              "source_sha256": {name: sha(Path(__file__).parents[1] / "app/modules/knowledge" / name)
                                for name in ("topic_prototypes.py", "router.py", "evidence_routing.py")},
              "limits": manifest["limits"] + ["Prototypes are shadow representations of sampled content, with no generated summaries or production writes.",
                                               "All prototype points are considered to reproduce per-KB grouped maxima; legacy keeps its original Top30 budget.",
                                               "Existing corpus was inspected during development; this is a diagnostic, not a blind holdout."]}
    write_json(output / "report.json", report)
    return {"output": str(output), "policies": {key: {k: v for k, v in policy.items() if k != "cases"}
                                                for key, policy in policies.items()}}


async def capture_samples(snapshot: Path, output: Path, qdrant_url: str) -> dict:
    """Read actual production samples/clusters without enrichment or summaries."""
    from app.modules.ingestion.storage.vector_store import VectorStore
    from app.modules.knowledge.portraits import PortraitGenerator
    from qdrant_client import QdrantClient
    from threadpoolctl import threadpool_limits

    _, _, portraits, *_ = load_snapshot(snapshot)
    expected = digest(json.loads((snapshot / "content.json").read_text()))

    def current_content_digest():
        return digest([{"collection": collection, **row} for collection in COLLECTIONS
                       for row in scroll(qdrant_url, collection, vectors=False)])

    require(current_content_digest() == expected, "content no longer matches frozen evidence")
    output.mkdir(parents=True, exist_ok=False)

    def forbidden(*args, **kwargs):
        raise RuntimeError("shadow sampling prohibits Qdrant writes")

    records = []
    with ExitStack() as stack:
        for name in ("create_collection", "delete_collection", "update_collection", "upsert", "delete", "set_payload",
                     "overwrite_payload", "clear_payload", "delete_payload", "create_payload_index"):
            stack.enter_context(patch.object(QdrantClient, name, forbidden))
        stack.enter_context(threadpool_limits(limits=1))
        generator = PortraitGenerator.__new__(PortraitGenerator)
        generator.vector_store = VectorStore(initialize_collections=False)
        generator.vector_store.client.close()
        generator.vector_store.client = QdrantClient(url=qdrant_url)
        try:
            for kb_id in sorted({row["payload"]["kb_id"] for row in portraits}):
                started = time.perf_counter()
                samples = await generator._sample_vectors(kb_id)
                clustering = await generator._perform_clustering(samples)
                with (output / f"{kb_id}.npy").open("xb") as stream:
                    np.save(stream, np.asarray([sample.vector for sample in samples], dtype=np.float32), allow_pickle=False)
                metadata = [{key: value for key, value in asdict(sample).items() if key != "vector"} for sample in samples]
                elapsed = time.perf_counter() - started
                write_json(output / f"{kb_id}.json", {"kb_id": kb_id, "samples": metadata,
                                                     "clustering": clustering, "duration_seconds": elapsed})
                records.append({"kb_id": kb_id, "samples": len(samples), "clusters": clustering["k"], "seconds": elapsed})
        finally:
            generator.vector_store.client.close()
    require(current_content_digest() == expected, "content changed during sampling")
    backend = Path(__file__).parents[1]
    write_json(output / "manifest.json", {"source_snapshot_manifest_sha256": sha(snapshot / "manifest.json"),
                                         "kbs": records, "content_digest": expected,
                                         "files": {path.name: sha(path) for path in sorted(output.iterdir())},
                                         "source_sha256": {name: sha(backend / name) for name in
                                                           ("app/modules/knowledge/portraits.py", "app/modules/ingestion/storage/vector_store.py")},
                                         "limits": "Actual production sampling and KMeans; no metadata enrichment, no summaries, no production writes."})
    return {"output": str(output), "kbs": len(records), "samples": sum(record["samples"] for record in records)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--snapshot", type=Path, required=True)
    parser.add_argument("--samples", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--capture-samples", action="store_true", help="Read source vectors and run production sampling/KMeans, without LLMs or writes")
    parser.add_argument("--qdrant-url", default="http://127.0.0.1:6333")
    args = parser.parse_args(argv)
    require(args.capture_samples or args.samples is not None, "--samples is required for replay")
    operation = (capture_samples(args.snapshot, args.output, args.qdrant_url) if args.capture_samples
                 else replay(args.snapshot, args.samples, args.output))
    print(json.dumps(asyncio.run(operation), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
